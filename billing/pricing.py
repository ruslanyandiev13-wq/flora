"""
Тариф (ТЗ "Биллинг / История", раздел 2). Единый тариф без вариантов.

Размер месячного пакета токенов выведен из целевой выручки, а не задан
произвольным числом - см. формулу ниже. Входные параметры (объём
накладных/мес, средняя сложность) взяты из реальной выборки 19 обработанных
накладных на момент написания ТЗ.

⚠️ ТЗ прямо просит пересчитать эти параметры ещё раз после 1-2 месяцев боевой
эксплуатации - 19 замеров всё ещё скромная выборка. Когда будут реальные
цифры - поменять константы ниже, остальное пересчитается само.
"""

AVG_INVOICES_PER_MONTH = 200
# Средняя сложность по реальной выборке из 19 накладных - точное значение
# (не округлённые "~6,5" из текста ТЗ), т.к. именно оно даёт пакет 1720,
# указанный в ТЗ явно (DEFAULT 1720 в схеме БД, 172 = 10% в разделе 5.1).
AVG_COMPLEXITY_PER_INVOICE = 6.45
BUFFER_RATIO = 0.75                # доля пакета, которую расход должен занимать в среднем месяце
TARGET_MONTHLY_REVENUE_RUB = 60000

MIN_TOPUP_TOKENS = 100             # минимальный объём ручной докупки за раз

# Цена докупки токена сверх пакета, ₽ (ТЗ, раздел 6.1) - задана явно, а не
# выведена из целевой выручки: это розничная цена докупки, отдельная от
# "себестоимости" токена внутри подписки.
PRICE_PER_TOKEN_RUB = 40

_actual_monthly_consumption = AVG_INVOICES_PER_MONTH * AVG_COMPLEXITY_PER_INVOICE

# Пакет токенов, включённый в подписку каждый месяц (округлён до целого).
MONTHLY_TOKEN_PACKAGE = round(_actual_monthly_consumption / BUFFER_RATIO)
